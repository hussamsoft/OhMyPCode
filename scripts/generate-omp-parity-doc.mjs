#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const manifestModulePath = path.join(root, "packages", "app", "src", "omp-parity", "manifest.ts");
const docPath = path.join(root, "docs", "omp", "PARITY.md");

if (!fs.existsSync(manifestModulePath)) {
  console.error(`Manifest file not found: ${manifestModulePath}`);
  process.exit(1);
}

// Read and parse manifest entries
const manifestContent = fs.readFileSync(manifestModulePath, "utf8");
const jsonMatch = manifestContent.match(
  /export const OMP_PARITY_MANIFEST: readonly OmpParityEntry\[\] = (\[[\s\S]*?\]) as const;/,
);
if (!jsonMatch) {
  console.error("Could not parse OMP_PARITY_MANIFEST from manifest.ts");
  process.exit(1);
}

// Evaluate rather than JSON.parse: the manifest is TypeScript, so keys may be
// unquoted and a value may be a bare `undefined`. Both are legal in a literal
// and both are JSON syntax errors, so parsing it as JSON would couple this
// generator to whichever quote style the formatter last chose.
const entries = new Function(`return ${jsonMatch[1]}`)();

function generateMarkdown(items) {
  let md = "# OMP Parity Documentation\n\n";
  md += `Machine-checked parity contract generated by \`scripts/generate-omp-parity-doc.mjs\` from \`packages/app/src/omp-parity/manifest.ts\`.\n`;
  md += `Total tracked entries: **${items.length}**.\n\n`;

  md += "| Surface | Name | Transport | GUI Home | Capability |\n";
  md += "|---|---|---|---|---|\n";

  for (const entry of items) {
    const capability = entry.capability ? `\`${entry.capability}\`` : "—";
    md += `| \`${entry.surface}\` | \`${entry.name}\` | \`${entry.transport}\` | \`${entry.guiHome}\` | ${capability} |\n`;
  }

  return md;
}

const generatedDoc = generateMarkdown(entries);
const isCheck = process.argv.includes("--check");

if (isCheck) {
  if (!fs.existsSync(docPath)) {
    console.error(
      `Error: ${docPath} does not exist. Run 'node scripts/generate-omp-parity-doc.mjs' to generate it.`,
    );
    process.exit(1);
  }
  const existing = fs.readFileSync(docPath, "utf8").replace(/\r\n/g, "\n");
  const normalizedGenerated = generatedDoc.replace(/\r\n/g, "\n");
  if (existing !== normalizedGenerated) {
    console.error(
      `Error: ${docPath} is out of date. Run 'node scripts/generate-omp-parity-doc.mjs' to update it.`,
    );
    process.exit(1);
  }
  console.log(
    `[parity:check] ${path.relative(root, docPath)} is up to date (${entries.length} entries).`,
  );
} else {
  fs.mkdirSync(path.dirname(docPath), { recursive: true });
  fs.writeFileSync(docPath, generatedDoc, "utf8");
  console.log(`Wrote ${path.relative(root, docPath)} with ${entries.length} rows.`);
}
