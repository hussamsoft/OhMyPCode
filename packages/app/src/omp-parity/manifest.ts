/**
 * OMP Parity Manifest — Machine-checked contract between OhMyPCode and OMP.
 * Hand-owned contract.
 */

interface OmpParityEntry {
  /** Unique identifier: "<surface>:<name>" */
  id: string;
  /** Surface category */
  surface:
    | "flag"
    | "subcommand"
    | "slash"
    | "rpc"
    | "tool"
    | "mode"
    | "setting"
    | "keybinding"
    | "composerTrigger"
    | "overlay"
    | "segment";
  /** Exact OMP identifier */
  name: string;
  /** Transport binding */
  transport: "rpc" | "session" | "settings" | "none" | "terminal";
  /** Application location (route, panel kind, or control ID) */
  guiHome: string;
  /** Server capability feature flag required for RPC transport */
  capability?: string;
  /**
   * The `omp.*.request` message that dispatches this command, for `rpc`
   * rows. Required whenever `guiHome` is not the terminal escape hatch:
   * a command the host cannot send is not reachable, whatever the row
   * claims. `omp.command.run.request` is the generic channel that carries
   * the RPC commands with no message of their own.
   */
  dispatch?: string;
  /** Rationale when mapped to terminal:omp-tui escape hatch */
  reason?: string;
}

